"""E6: toolkit-side serial cost of qualify per entry with a ZERO-latency stub transport (so only toolkit work is timed).
Run at several cohort sizes to see growth with review-event count / manifest size."""
import json, os, sys, tempfile, time, hashlib, cProfile, pstats, io
from pathlib import Path
sys.path.insert(0, os.getcwd())
from tools.diagnostics.ingest_benchmark import fixture
from tools.intake import cohort, store
from tools.catalog import catalog_store as catalog
from tools.review_events import event_store as events
n = int(sys.argv[1]); prof = len(sys.argv) > 2
def transport(model, messages):
    p = json.loads(messages[-1]["content"])
    return {"content": json.dumps({"decision": "accept", "inspected_records": [r["i"] for r in p["records"]],
            "inspected_warnings": [w["ref"] for w in p["warnings"]], "contradictions": [], "missing_evidence": [],
            "explanation": "ok"}), "usage": {"prompt_tokens": 10, "completion_tokens": 5}}
with tempfile.TemporaryDirectory(dir=os.environ["TMPDIR"]) as t:
    t = Path(t); root, inbox = t/"i", t/"in"; root.mkdir()
    store.initialize(root); catalog.initialize(root); events.initialize(root)
    (root/"config").mkdir(); (root/"config/policy.local.json").write_text(json.dumps({"audience": "authorized-local"}))
    (root/"documents").mkdir(); (root/"documents/context.md").write_text("# Ctx\nctx\n")
    fixture(inbox, n, seed="q", padding=3, mixed=None)   # small docs: ~12 records each
    kw = dict(system="bench", actor="b", policy_path="config/standing-policy.local.json", manifest="config/selection.local.json",
              model="m", transport=transport, context=["documents/context.md"])
    # policy must name reviewer usai:m ; generated by qualify (scope D1..D2500 so keep n<=2500)
    t0 = time.perf_counter(); rep = cohort.ingest(root, inbox, system="bench", actor="b"); ing = time.perf_counter()-t0
    stamps = []
    orig = cohort._review_and_select
    def timed(*a, **k):
        s = time.perf_counter(); r = orig(*a, **k); stamps.append(time.perf_counter()-s); return r
    cohort._review_and_select = timed
    pr = cProfile.Profile() if prof else None
    t1 = time.perf_counter()
    if pr: pr.enable()
    rep = cohort.qualify(root, inbox, concurrency=1, **kw)
    if pr: pr.disable()
    tot = time.perf_counter()-t1
    q = len(stamps); dec = lambda a: sum(a)/max(1,len(a))*1e3
    print(json.dumps({"docs": n, "ingest_s": round(ing,1), "qualify_total_s": round(tot,1), "qualification": rep["counts"].get("qualification"),
          "review_select_ms_per_entry_first_decile": round(dec(stamps[:q//10]),1), "last_decile": round(dec(stamps[-q//10:]),1), "mean": round(dec(stamps),1),
          "ledger_MB": (root/".local/intake/intake.sqlite3").stat().st_size>>20, "events_MB": (root/".local/review-events/events.sqlite3").stat().st_size>>20}))
    step = max(1, q//12)
    print("per-entry serial toolkit ms by position:", [(i, round(dec(stamps[i:i+step]))) for i in range(0, q, step)])
    if pr:
        s = io.StringIO(); pstats.Stats(pr, stream=s).sort_stats("cumulative").print_stats(28); print(s.getvalue()[:5500])
